"use client";

import { useState, Suspense } from "react";
import { useSearchParams, useRouter } from "next/navigation";
import Link from "next/link";
import { toast } from "sonner";
import { ShieldCheck, KeyRound, ArrowRight, ArrowLeft, AlertCircle } from "lucide-react";
import { Input } from "@/components/ui/input";
import { Button } from "@/components/ui/button";
import { Label } from "@/components/ui/label";
import { Card, CardContent } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { Skeleton } from "@/components/ui/skeleton";
import { useAuthStore } from "@/store/authStore";
import { post, extractApiError } from "@/lib/api";
import type { AuthTokens, User } from "@/lib/types";

function TwoFactorInner() {
  const searchParams = useSearchParams();
  const router = useRouter();
  const loginToken = searchParams.get("loginToken");
  const setAuth = useAuthStore((s) => s.setAuth);
  const [code, setCode] = useState("");
  const [isSubmitting, setIsSubmitting] = useState(false);

  async function handleVerify(e?: React.FormEvent) {
    if (e) e.preventDefault();
    if (!loginToken) {
      toast.error("Session expired. Please sign in again.");
      router.push("/login");
      return;
    }
    if (code.length !== 6) {
      toast.error("Please enter the full 6-digit security code.");
      return;
    }
    setIsSubmitting(true);
    try {
      const res = await post<{ user: User } & AuthTokens>("/auth/2fa/verify", {
        loginToken,
        code,
      });
      setAuth(res.data.user, {
        accessToken: res.data.accessToken,
        refreshToken: res.data.refreshToken,
        expiresIn: res.data.expiresIn,
      });
      toast.success("Identity verified! Welcome back.");
      router.push("/calls/dialpad");
    } catch (err) {
      toast.error(extractApiError(err).message);
      setCode("");
    } finally {
      setIsSubmitting(false);
    }
  }

  return (
    <div className="space-y-6">
      <div className="space-y-2 text-center sm:text-left">
        <Badge variant="secondary" className="text-xs font-mono">
          Two-Factor Authentication
        </Badge>
        <h1 className="text-2xl sm:text-3xl font-extrabold tracking-tight text-foreground">
          Confirm your identity
        </h1>
        <p className="text-xs sm:text-sm text-muted-foreground">
          Enter the 6-digit verification code generated by your authenticator app (Google Authenticator, Authy, or 1Password).
        </p>
      </div>

      <Card className="rounded-3xl border border-border/80 bg-card shadow-xl overflow-hidden backdrop-blur">
        <CardContent className="p-6 sm:p-8 space-y-6">
          {!loginToken ? (
            <div className="rounded-2xl border border-destructive/30 bg-destructive/10 p-5 text-center space-y-3">
              <div className="mx-auto flex h-12 w-12 items-center justify-center rounded-full bg-destructive/20 text-destructive">
                <AlertCircle className="h-6 w-6" />
              </div>
              <h3 className="text-base font-bold text-foreground">Session Expired</h3>
              <p className="text-xs text-muted-foreground">
                Your sign-in authorization session has expired. Please log in again to generate a new 2FA token.
              </p>
              <Link
                href="/login"
                className="inline-flex items-center justify-center gap-1.5 rounded-xl bg-primary px-4 py-2 text-xs font-semibold text-primary-foreground shadow-sm"
              >
                <span>Back to Sign In</span>
                <ArrowRight className="h-3.5 w-3.5" />
              </Link>
            </div>
          ) : (
            <form onSubmit={handleVerify} className="space-y-5">
              <div className="space-y-2">
                <Label htmlFor="twofa-code" className="text-xs font-semibold text-center block">
                  6-Digit Authenticator Code
                </Label>
                <div className="relative">
                  <KeyRound className="absolute left-3.5 top-1/2 -translate-y-1/2 h-4 w-4 text-muted-foreground pointer-events-none" />
                  <Input
                    id="twofa-code"
                    type="text"
                    inputMode="numeric"
                    autoComplete="one-time-code"
                    maxLength={6}
                    placeholder="000 000"
                    value={code}
                    onChange={(e) => setCode(e.target.value.replace(/[^0-9]/g, ""))}
                    className="pl-10 h-14 rounded-2xl bg-muted/40 border-border/80 focus-visible:ring-primary/40 text-center text-2xl font-mono tracking-[0.35em] font-bold"
                    autoFocus
                  />
                </div>
                <p className="text-[11px] text-muted-foreground text-center">
                  Codes refresh every 30 seconds.
                </p>
              </div>

              <Button
                type="submit"
                className="w-full h-11 rounded-xl bg-primary hover:bg-primary/90 text-primary-foreground font-semibold shadow-md text-sm gap-2"
                disabled={isSubmitting || code.length !== 6}
              >
                <ShieldCheck className="h-4 w-4" />
                <span>{isSubmitting ? "Authenticating..." : "Verify & Continue"}</span>
              </Button>
            </form>
          )}
        </CardContent>
      </Card>

      <div className="text-center text-xs text-muted-foreground">
        <Link href="/login" className="hover:text-foreground transition-colors font-medium inline-flex items-center gap-1">
          <ArrowLeft className="h-3.5 w-3.5" />
          <span>Return to login</span>
        </Link>
      </div>
    </div>
  );
}

export default function VerifyTwoFactorPage() {
  return (
    <Suspense
      fallback={
        <div className="space-y-4">
          <Skeleton className="h-10 w-48 rounded-xl" />
          <Skeleton className="h-64 w-full rounded-3xl" />
        </div>
      }
    >
      <TwoFactorInner />
    </Suspense>
  );
}
